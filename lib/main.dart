class Alice1000Home extends StatefulWidget {
  const Alice1000Home({super.key});
  @override
  State<Alice1000Home> createState() => _Alice1000HomeState();
}

class _Alice1000HomeState extends State<Alice1000Home> {
  final picker = ImagePicker();
  int estrelas = 0;
  int robux = 0;
  Map<String, bool> feitas = {};
  String filtro = '';
  String mundoSelecionado = 'Mundo 1 - Acordar e Casa 🌞';

  @override
  void initState() { super.initState(); carregar(); }
  Future<void> carregar() async {
    final p = await SharedPreferences.getInstance();
    setState(() { estrelas = p.getInt('estrelas') ?? 0; robux = p.getInt('robux') ?? 0; });
  }
  Future<void> salvar() async {
    final p = await SharedPreferences.getInstance();
    await p.setInt('estrelas', estrelas);
    await p.setInt('robux', robux);
  }

  List<String> get tarefasFiltradas {
    var lista = atividades1000[mundoSelecionado] ?? [];
    if (filtro.isEmpty) return lista;
    return lista.where((t) => t.toLowerCase().contains(filtro.toLowerCase())).toList();
  }

  Future<void> fazer(String tarefa) async {
    final XFile? img = await picker.pickImage(source: ImageSource.camera, imageQuality: 50);
    if (img != null) {
      setState(() { feitas[tarefa] = true; estrelas += 1; robux += 1; });
      salvar();
      if (mounted) ScaffoldMessenger.of(context).showSnackBar(SnackBar(content: Text('✅ $tarefa +1 ⭐'), backgroundColor: const Color(0xFF7C4DFF)));
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        backgroundColor: const Color(0xFF7C4DFF),
        foregroundColor: Colors.white,
        title: const Text('Alice - 1000 Atividades'),
        actions: [Padding(padding: const EdgeInsets.all(12), child: Center(child: Text('⭐$estrelas  R\$ $robux  |  ${feitas.length}/1000', style: const TextStyle(fontWeight: FontWeight.bold))))],
      ),
      body: Column(
        children: [
          Container(
            color: Colors.white,
            padding: const EdgeInsets.all(8),
            child: Column(children: [
              DropdownButton<String>(
                value: mundoSelecionado,
                isExpanded: true,
                items: atividades1000.keys.map((m) => DropdownMenuItem(value: m, child: Text(m, style: const TextStyle(fontSize: 14)))).toList(),
                onChanged: (v) => setState(() => mundoSelecionado = v!),
              ),
              TextField(
                decoration: const InputDecoration(prefixIcon: Icon(Icons.search), hintText: 'Buscar nas 1000 atividades...', border: OutlineInputBorder()),
                onChanged: (v) => setState(() => filtro = v),
              ),
              const SizedBox(height: 4),
              Text('${tarefasFiltradas.length} atividades neste filtro - ${feitas.length} feitas no total', style: const TextStyle(fontSize: 12, color: Colors.grey)),
            ]),
          ),
          Expanded(
            child: ListView.builder(
              itemCount: tarefasFiltradas.length,
              itemBuilder: (_, i) {
                String t = tarefasFiltradas[i];
                bool feita = feitas[t] == true;
                return Card(
                  color: feita ? Colors.green[50] : Colors.white,
                  child: ListTile(
                    leading: Icon(feita ? Icons.check_circle : Icons.circle_outlined, color: feita ? Colors.green : const Color(0xFFE040FB)),
                    title: Text(t, style: TextStyle(fontSize: 14, decoration: feita ? TextDecoration.lineThrough : null)),
                    trailing: ElevatedButton.icon(
                      style: ElevatedButton.styleFrom(backgroundColor: const Color(0xFFE040FB), foregroundColor: Colors.white, padding: const EdgeInsets.symmetric(horizontal: 8)),
                      onPressed: () => fazer(t),
                      icon: const Icon(Icons.camera_alt, size: 16),
                      label: Text(feita ? 'TROCAR' : 'FIZ! 📸', style: const TextStyle(fontSize: 11)),
                    ),
                  ),
                );
              },
            ),
          ),
        ],
      ),
    );
  }
}
